//
//  WebDavSyncContractTests.swift
//  MobileOrg
//
//  Regression harness for the WebDAV sync path (GPL-2.0, like the rest of
//  the project). Each test pins one sync contract as *observable fixture
//  traffic* using tinydav's control plane, which restores a pristine fixture
//  profile per test and serves a queryable request log — so tests are
//  order-independent, unlike the shared-state runs that made the old lane
//  unstable.
//
//  The five contracts (sync proof-run findings) and their witnesses:
//
//  1. A second sync with no new local edits performs no mobileorg.org
//     GET or PUT                    — fixture log window of the second sync.
//  2. A locally-flagged-but-identical merge is not uploaded
//                                   — GET present, PUT absent on that sync.
//  3. A transfer aborted mid-download must not wipe the aborted file's
//     outline                       — node counts after a test-side abort.
//  4. Concurrent sync entrypoints run single-flight
//                                   — exactly one checksums.dat GET.
//  5. The app never writes the staged Org files
//                                   — no write methods + byte-identity.
//
//  Plus the golden import of the owner-shaped (synthetic) profile: the
//  category/epic/task hierarchy with :ID: bindings, and a captured note
//  round-tripping through mobileorg.org in both directions.
//
//  Fixture layout: MobileOrgTests/Resources/WebDavTests/pristine/<profile>/
//  (generated by Tools/fixtures/build_golden_fixtures.py, which also wrote
//  the golden-manifest.json served by the control plane). The app-side
//  settings point at the loopback IP literal — the iOS 26 simulator does not
//  consult the host's /etc/hosts (CI run 39841570360).
//
//  This file also hosts WebDavSyncTestCase, the shared base class for all
//  WebDAV sync suites (the legacy WebDavTests subclasses it too).

import XCTest
import CoreData
import CommonCrypto

@testable import MobileOrg

// MARK: - Fixture plumbing

enum FixtureError: Error {
  case badStatus(Int, String)
}

enum WebDavFixture {
  static let webDavHost = "https://127.0.0.1:32773"
  static let controlHost = "http://127.0.0.1:32774"
  static let username = "schnuddelhuddel"
  static let password = "schnuddelhuddel"
}

/// URLSession delegate accepting any server certificate — the fixture serves
/// a fresh self-signed TLS cert per launch. Mirrors the app's own
/// WebDavTransferManager challenge handling.
class TrustAnySessionDelegate: NSObject, URLSessionDelegate {
  func urlSession(_ session: URLSession,
                  didReceive challenge: URLAuthenticationChallenge,
                  completionHandler: @escaping (URLSession.AuthChallengeDisposition, URLCredential?) -> Void) {
    guard challenge.protectionSpace.authenticationMethod == NSURLAuthenticationMethodServerTrust,
          let trust = challenge.protectionSpace.serverTrust else {
      completionHandler(.performDefaultHandling, nil)
      return
    }
    completionHandler(.useCredential, URLCredential(trust: trust))
  }
}

struct FixtureRequest: Codable, Equatable {
  let seq: Int
  let method: String
  let path: String
}

struct GoldenStructureEntry: Codable {
  let level: Int
  let heading: String
  let todo: String?
  let priority: String?
  let tags: String?
  let id: String?
}

struct GoldenFile: Codable {
  let count: Int
  let headings: Int
  let md5: String
  let structure: [GoldenStructureEntry]
}

struct GoldenManifest: Codable {
  let profile: String
  let totalNodes: Int
  let indexFile: String
  let stagedFiles: [String]
  let files: [String: GoldenFile]
}

// MARK: - Shared base class for WebDAV sync suites

class WebDavSyncTestCase: XCTestCase {

  var moc: NSManagedObjectContext?

  /// Call from the subclass setUp: fresh in-memory Core Data stack plus
  /// app settings pointed at the fixture.
  func configureSyncTest(encryptionPassword: String) {
    moc = setUpInMemoryManagedObjectContext()
    PersistenceStack.shared.moc = moc!
    setUpSyncSettings(encryptionPassword: encryptionPassword)
  }

  /// In-memory Core Data stack for sync tests (matches the app's model).
  func setUpInMemoryManagedObjectContext() -> NSManagedObjectContext {
    let path = Bundle.main.path(forResource: "MobileOrg2", ofType: "momd")
    let momURL = URL(fileURLWithPath: path!)
    let managedObjectModel = NSManagedObjectModel(contentsOf: momURL)

    let persistentStoreCoordinator = NSPersistentStoreCoordinator(managedObjectModel: managedObjectModel!)
    try! persistentStoreCoordinator.addPersistentStore(ofType: NSInMemoryStoreType, configurationName: nil, at: nil, options: nil)

    let managedObjectContext = NSManagedObjectContext(concurrencyType: .mainQueueConcurrencyType)
    managedObjectContext.persistentStoreCoordinator = persistentStoreCoordinator

    return managedObjectContext
  }

  /// Point the app at the fixture over the loopback IP literal. Every sync
  /// test suite MUST call this (via configureSyncTest): Settings is a
  /// process-wide singleton, and the fixture's profiles are unencrypted
  /// unless stated.
  func setUpSyncSettings(encryptionPassword: String) {
    Settings.instance().serverMode = ServerModeWebDav
    Settings.instance().username = WebDavFixture.username
    Settings.instance().password = WebDavFixture.password
    // Loopback IP literal, not the fixture hostname: the iOS 26 simulator's
    // resolver does not consult the host's /etc/hosts, and the fixture name
    // is a wildcard record pointing at GitHub Pages, so a hostname URL
    // resolves to a server that is not the fixture and sync silently
    // downloads nothing (CI run 39841570360).
    Settings.instance().indexUrl = URL(string: "\(WebDavFixture.webDavHost)/index.org")
    Settings.instance().encryptionPassword = encryptionPassword
  }

  // MARK: Control plane (plain HTTP on loopback)

  private func controlRequest(path: String, method: String) throws -> Data {
    let request = URLRequest(url: URL(string: "\(WebDavFixture.controlHost)\(path)")!)
    request.httpMethod = method
    request.setValue("Basic \(basicAuthHeader)", forHTTPHeaderField: "Authorization")
    return try fixtureHttpSend(request, viaWebDavSession: false, description: path)
  }

  private var basicAuthHeader: String {
    let credentials = "\(WebDavFixture.username):\(WebDavFixture.password)"
    return Data(credentials.utf8).base64EncodedString()
  }

  /// Restore the pristine profile and clear the fixture request log.
  /// Returns the log cutoff the test should query from.
  func resetFixture(profile: String) throws -> Int {
    let data = try controlRequest(path: "/reset?profile=\(profile)", method: "POST")
    let json = try XCTUnwrap(try JSONSerialization.jsonObject(with: data) as? [String: Any])
    return try XCTUnwrap(json["since"] as? Int)
  }

  func fixtureRequests(since: Int) throws -> [FixtureRequest] {
    let data = try controlRequest(path: "/log?since=\(since)", method: "GET")
    let json = try XCTUnwrap(try JSONSerialization.jsonObject(with: data) as? [String: Any])
    let raw = try XCTUnwrap(json["requests"] as? [[String: Any]])
    return try raw.map { entry in
      FixtureRequest(seq: try XCTUnwrap(entry["seq"] as? Int),
                     method: try XCTUnwrap(entry["method"] as? String),
                     path: try XCTUnwrap(entry["path"] as? String))
    }
  }

  func goldenManifest(profile: String) throws -> GoldenManifest {
    let data = try controlRequest(path: "/golden?profile=\(profile)", method: "GET")
    return try JSONDecoder().decode(GoldenManifest.self, from: data)
  }

  /// Highest logged sequence after `cutoff` — the boundary for the next
  /// traffic window.
  func latestSequence(after cutoff: Int) throws -> Int {
    let entries = try fixtureRequests(since: cutoff)
    return entries.map(\.seq).max() ?? cutoff
  }

  // MARK: App-facing WebDAV (TLS, like the app uses)

  private lazy var fixtureWebDavSession: URLSession = {
    URLSession(configuration: .ephemeral, delegate: TrustAnySessionDelegate(), delegateQueue: nil)
  }()

  func fetchFixtureFile(_ name: String) throws -> Data {
    var request = URLRequest(url: URL(string: "\(WebDavFixture.webDavHost)/\(name)")!)
    request.httpMethod = "GET"
    request.setValue("Basic \(basicAuthHeader)", forHTTPHeaderField: "Authorization")
    return try fixtureHttpSend(request, viaWebDavSession: true, description: "GET \(name)")
  }

  /// Test-side server mutation (staging changes happen on the server, the
  /// way Emacs would push them — the app itself must never do this).
  func putFixtureFile(_ name: String, contents: Data) throws {
    var request = URLRequest(url: URL(string: "\(WebDavFixture.webDavHost)/\(name)")!)
    request.httpMethod = "PUT"
    request.setValue("Basic \(basicAuthHeader)", forHTTPHeaderField: "Authorization")
    request.httpBody = contents
    _ = try fixtureHttpSend(request, viaWebDavSession: true, description: "PUT \(name)")
  }

  /// Server-side staging change, the way Emacs would push it: replace the
  /// file AND refresh its checksums.dat entry — the app downloads a staged
  /// file only when its checksum line changed (SyncManager compares the
  /// parsed checksum against its local record). A bare PUT would be ignored,
  /// which is correct app behavior, not a bug.
  func updateFixtureFile(_ name: String, contents: Data) throws {
    try putFixtureFile(name, contents: contents)
    var checksums = String(decoding: try fetchFixtureFile("checksums.dat"), as: UTF8.self)
    let pattern = "(?m)^[0-9a-f]{32}  \(NSRegularExpression.escapedPattern(for: name))$"
    guard let range = checksums.range(of: pattern, options: .regularExpression) else {
      XCTFail("checksums.dat has no checksum line for \(name)")
      return
    }
    checksums.replaceSubrange(range, with: "\(md5Hex(contents))  \(name)")
    try putFixtureFile("checksums.dat", contents: Data(checksums.utf8))
  }

  private func fixtureHttpSend(_ request: URLRequest, viaWebDavSession: Bool,
                               description: String) throws -> Data {
    var result = Result<Data, Error>.failure(FixtureError.badStatus(-1, description))
    let semaphore = DispatchSemaphore(value: 0)
    let session = viaWebDavSession ? fixtureWebDavSession : URLSession.shared
    let task = session.dataTask(with: request) { data, response, error in
      if let error {
        result = .failure(error)
      } else if let httpResponse = response as? HTTPURLResponse,
                !(200..<300).contains(httpResponse.statusCode) {
        result = .failure(FixtureError.badStatus(httpResponse.statusCode, description))
      } else {
        result = .success(data ?? Data())
      }
      semaphore.signal()
    }
    task.resume()
    semaphore.wait()
    return try result.get()
  }

  // MARK: Sync orchestration

  /// Register a SyncComplete observer and return a fulfillable handle for
  /// waiting on an already-running sync.
  func makeSyncCompleteExpectation() -> XCTestExpectation {
    let completed = expectation(description: "SyncComplete")
    let observer = NotificationCenter.default.addObserver(
      forName: NSNotification.Name("SyncComplete"), object: nil, queue: nil) { _ in
      completed.fulfill()
    }
    addTeardownBlock {
      NotificationCenter.default.removeObserver(observer)
    }
    return completed
  }

  /// Start a sync and wait for SyncComplete. Replaces the old fixed-tick
  /// pattern (asyncAfter + generous deadline) with an actual completion
  /// expectation; the sync pipeline posts SyncComplete from any thread, and
  /// fulfillment is thread-safe.
  func syncAndWait(timeout: TimeInterval = 60,
                   file: StaticString = #filePath, line: UInt = #line) {
    let completed = makeSyncCompleteExpectation()
    SyncManager.instance().sync()
    wait(for: [completed], timeout: timeout, file: file, line: line)
  }

  /// Poll the fixture log until at least `count` matching requests have been
  /// observed (or fail on timeout).
  func waitForFixtureRequests(count: Int, method: String?, path: String, since: Int,
                              timeout: TimeInterval = 30,
                              file: StaticString = #filePath, line: UInt = #line) {
    let description = method.map { "\(count)x \($0) \(path)" } ?? "requests to \(path)"
    let predicate = NSPredicate { _, _ in
      guard let entries = try? self.fixtureRequests(since: since) else { return false }
      let matching = entries.filter { $0.path == path && (method == nil || $0.method == method!) }
      return matching.count >= count
    }
    wait(for: [expectation(for: predicate, evaluatedWith: nil, description: description)],
         timeout: timeout, file: file, line: line)
  }

  // MARK: Node-store assertions

  func fetchNodes(matching predicate: NSPredicate? = nil) throws -> [Node] {
    let request = NSFetchRequest<Node>(entityName: "Node")
    request.predicate = predicate
    return try moc?.fetch(request) ?? []
  }

  func fetchSingleNode(heading: String,
                       file: StaticString = #filePath, line: UInt = #line) throws -> Node {
    let nodes = try fetchNodes(matching: NSPredicate(format: "heading == %@", heading))
    XCTAssertEqual(nodes.count, 1, "expected exactly one node titled \(heading)", file: file, line: line)
    return try XCTUnwrap(nodes.first, file: file, line: line)
  }

  func nodeCount(inFile name: String) throws -> Int {
    // Every node parsed from a file resolves to the file node as ancestor;
    // Node.ownerFile() returns that file node's heading (the filename).
    try fetchNodes().filter { $0.ownerFile() == name }.count
  }

  /// Whole-tree golden assertion: total node count plus per-file counts
  /// (each parsed file contributes one level-0 file node plus one node per
  /// heading), straight from the committed manifest.
  func assertNodeCounts(match manifest: GoldenManifest,
                        file: StaticString = #filePath, line: UInt = #line) {
    let allNodes = (try? fetchNodes()) ?? []
    XCTAssertEqual(allNodes.count, manifest.totalNodes, "total node count", file: file, line: line)
    for (name, golden) in manifest.files {
      let count = allNodes.filter { $0.ownerFile() == name }.count
      XCTAssertEqual(count, golden.count, "node count for \(name)", file: file, line: line)
    }
  }

  func md5Hex(_ data: Data) -> String {
    var digest = [UInt8](repeating: 0, count: Int(CC_MD5_DIGEST_LENGTH))
    data.withUnsafeBytes { buffer in
      _ = CC_MD5(buffer.baseAddress, CC_LONG(buffer.count), &digest)
    }
    return digest.map { String(format: "%02x", $0) }.joined()
  }
}

// MARK: - Contract tests (the five sync assertions + golden import)

final class WebDavSyncContractTests: WebDavSyncTestCase {

  override func setUp() {
    super.setUp()
    // The peter profile is plaintext, so the tests can read what the app
    // uploaded byte-for-byte.
    configureSyncTest(encryptionPassword: "")

    // Register the fixture's Org keyword groups up front, mirroring a
    // steady-state device: the app persists index-derived groups in
    // NSUserDefaults, and checksums.dat order can parse home.org.txt before
    // index.org registers its "#+TODO:" line, so extraction must not depend
    // on parse order.
    Settings.instance().resetPrimaryTagsAndTodoStates()
    let todoStates = NSMutableArray(array: ["NEXT", "TODO", "WAITING", "SOMEDAY"])
    let doneStates = NSMutableArray(array: ["DONE", "CANCELLED"])
    Settings.instance().addTodoStateGroup(NSMutableArray(array: [todoStates, doneStates]))
  }

  // (1) Second sync with no new local edits: no edits-file requests at all.
  func testSecondSyncWithNoNewEditsSkipsEditsFileRoundTrip() throws {
    let manifest = try goldenManifest(profile: "peter")
    let cutoff1 = try resetFixture(profile: "peter")

    syncAndWait()
    assertNodeCounts(match: manifest)

    let cutoff2 = try latestSequence(after: cutoff1)
    syncAndWait()

    let window = try fixtureRequests(since: cutoff2)
    XCTAssertTrue(window.contains { $0.method == "GET" && $0.path == "/checksums.dat" },
                  "the second sync did not run (no checksums.dat request in \(window))")
    XCTAssertFalse(window.contains { $0.path == "/mobileorg.org" },
                   "a second sync with no new edits must not fetch or upload the edits file (saw \(window))")
  }

  // (2) A flagged-but-unchanged merge must not be uploaded; the sync after
  // it returns to contract (1).
  func testUnchangedMergedEditsAreNotUploaded() throws {
    let manifest = try goldenManifest(profile: "peter")
    let cutoff1 = try resetFixture(profile: "peter")

    syncAndWait()
    assertNodeCounts(match: manifest)

    // The seeded capture was downloaded intact; flag it locally modified
    // without changing a byte — the double-capture shape.
    let notes = try XCTUnwrap(try moc?.fetch(NSFetchRequest<Note>(entityName: "Note")))
    XCTAssertEqual(notes.count, 1)
    notes[0].locallyModified = true
    Save()

    let cutoff2 = try latestSequence(after: cutoff1)
    syncAndWait()

    let window = try fixtureRequests(since: cutoff2)
    // The contract is "no upload of an unchanged merge". Whether the app
    // also re-fetches the edits file depends on its checksum bookkeeping
    // (a checksum-unchanged file is not re-downloaded), so only the PUT is
    // pinned here.
    XCTAssertEqual(window.filter { $0.method == "PUT" && $0.path == "/mobileorg.org" }.count, 0,
                   "an unchanged merge must not be uploaded (saw \(window))")

    let cutoff3 = try latestSequence(after: cutoff2)
    syncAndWait()
    let thirdWindow = try fixtureRequests(since: cutoff3)
    XCTAssertFalse(thirdWindow.contains { $0.path == "/mobileorg.org" },
                   "after the no-op upload, the next sync is back to contract (1) (saw \(thirdWindow))")
  }

  // (3) A transfer aborted mid-download must never wipe the aborted file's
  // outline. The abort lands at a racy moment by design; the invariant must
  // hold under every timing: old nodes or fully imported new nodes, never
  // an emptied tree.
  func testAbortedTransferLeavesNodesIntact() throws {
    let manifest = try goldenManifest(profile: "peter")
    let cutoff1 = try resetFixture(profile: "peter")

    syncAndWait()
    assertNodeCounts(match: manifest)

    // Server-side staging change, the way Emacs would push it (test-side
    // WebDAV PUT + checksums.dat refresh, deliberately outside the app).
    var grown = try fetchFixtureFile("scratchpad.org.txt")
    grown.append(Data("* Ship the harness notes\n".utf8))
    try updateFixtureFile("scratchpad.org.txt", contents: grown)

    let cutoff2 = try latestSequence(after: cutoff1)
    let completed = makeSyncCompleteExpectation()
    SyncManager.instance().sync()

    // Abort the moment the fixture sees the app re-fetch scratchpad.
    waitForFixtureRequests(count: 1, method: "GET", path: "/scratchpad.org.txt", since: cutoff2)
    SyncManager.instance().abort()

    // Whether the abort beat the download (failure path) or the transfer had
    // already finished (completion path), the pipeline reports completion.
    wait(for: [completed], timeout: 30)

    for name in ["home.org.txt", "work.org.txt"] {
      XCTAssertEqual(try nodeCount(inFile: name), manifest.files[name]!.count,
                     "\(name) must be untouched by the aborted scratchpad transfer")
    }
    let scratchpadGolden = manifest.files["scratchpad.org.txt"]!.count
    let scratchpadCount = try nodeCount(inFile: "scratchpad.org.txt")
    XCTAssertTrue(scratchpadCount == scratchpadGolden || scratchpadCount == scratchpadGolden + 1,
                  "scratchpad nodes must be the intact old set or the fully imported new set — never wiped (got \(scratchpadCount))")
  }

  // (4) Overlapping sync entrypoints must coalesce into a single flight.
  func testConcurrentSyncEntrypointsRunSingleFlight() throws {
    let manifest = try goldenManifest(profile: "peter")
    let cutoff = try resetFixture(profile: "peter")

    let completed = makeSyncCompleteExpectation()
    SyncManager.instance().sync()
    SyncManager.instance().sync() // same-tick re-entry: must be a no-op

    wait(for: [completed], timeout: 60)

    let window = try fixtureRequests(since: cutoff)
    XCTAssertEqual(window.filter { $0.method == "GET" && $0.path == "/checksums.dat" }.count, 1,
                   "overlapping sync entrypoints must run single-flight (saw \(window))")
    assertNodeCounts(match: manifest)
  }

  // (5) The app must never write the staged Org files. A real local edit
  // (tagging a task) round-trips only through mobileorg.org.
  func testAppNeverWritesStagedFiles() throws {
    let manifest = try goldenManifest(profile: "peter")
    let cutoff1 = try resetFixture(profile: "peter")

    syncAndWait()
    assertNodeCounts(match: manifest)

    // Real user flow: tag a task with a :ID: binding, then sync.
    let node = try fetchSingleNode(heading: "Call three contractors for quotes")
    XCTAssertEqual(node.nodeId, "11111111-1111-4111-8111-111111111111",
                   "the :ID: line must bind the task node for edit round-trips")
    let tagEditor = TagEditController(node: node)
    tagEditor?.recentTagString = "Test456"
    tagEditor?.commitNewTag()
    Save()

    let cutoff2 = try latestSequence(after: cutoff1)
    syncAndWait()

    let window = try fixtureRequests(since: cutoff2)
    let writeMethods = ["PUT", "POST", "DELETE", "MKCOL", "PROPPATCH", "LOCK", "MOVE", "COPY"]
    for name in manifest.stagedFiles {
      let staged = window.filter { $0.path == "/\(name)" }
      XCTAssertTrue(staged.allSatisfy { !writeMethods.contains($0.method) },
                    "the app must never write staged file \(name) (saw \(staged))")
      let served = try fetchFixtureFile(name)
      XCTAssertEqual(md5Hex(served), manifest.files[name]!.md5,
                     "staged file \(name) must be byte-identical after a sync that pushed edits")
    }
    XCTAssertEqual(window.filter { $0.method == "PUT" && $0.path == "/mobileorg.org" }.count, 1,
                   "the tag edit must upload exactly one edits-file PUT (saw \(window))")
  }

  // (6) A captured note round-trips: it uploads as a mobileorg.org entry and
  // is re-imported locally as a synced (unmodified) note.
  func testCapturedNoteRoundTripsThroughEditsFile() throws {
    let manifest = try goldenManifest(profile: "peter")
    _ = try resetFixture(profile: "peter")

    syncAndWait()
    assertNodeCounts(match: manifest)

    // Capture flow — mirrors AddNoteViewController's creation path.
    let noteId = "9e0e6f3c-1111-4222-8333-444455556666"
    let note = try XCTUnwrap(
      NSEntityDescription.insertNewObject(forEntityName: "Note", into: moc!) as? Note)
    note.text = "Rain barrel overflow fix near the shed"
    note.noteId = noteId
    note.createdAt = Date()
    note.locallyModified = true
    Save()

    syncAndWait()

    let serverEdits = String(decoding: try fetchFixtureFile("mobileorg.org"), as: UTF8.self)
    XCTAssertTrue(serverEdits.contains("* Rain barrel overflow fix near the shed"),
                  "the captured note must upload as a mobileorg.org entry (got: \(serverEdits))")
    XCTAssertTrue(serverEdits.contains("** Note ID: \(noteId)"),
                  "the capture must carry its note ID (got: \(serverEdits))")

    // Locally the note was deleted after upload and re-imported from the
    // merged file as a synced note.
    let notes = try XCTUnwrap(try moc?.fetch(NSFetchRequest<Note>(entityName: "Note")))
    XCTAssertEqual(notes.count, 2, "the seeded note plus the round-tripped capture")
    let roundTripped = notes.first { $0.noteId == noteId }
    XCTAssertEqual(roundTripped?.locallyModified?.boolValue, false,
                   "a re-imported capture is no longer locally modified")
    XCTAssertEqual(roundTripped?.text, "Rain barrel overflow fix near the shed")
  }

  // (7) The golden import reflects the owner's real-world shape: category →
  // epic → task hierarchy with todo states, priorities, and :ID: bindings —
  // everything straight from the generated manifest.
  func testImportReflectsCategoryEpicTaskHierarchy() throws {
    let manifest = try goldenManifest(profile: "peter")
    _ = try resetFixture(profile: "peter")

    syncAndWait()
    assertNodeCounts(match: manifest)

    // Every heading of every file lands at the right level with the right
    // extracted todo state, priority, tags, and :ID: binding.
    for (name, golden) in manifest.files {
      for entry in golden.structure {
        let nodes = try fetchNodes(matching: NSPredicate(
          format: "heading == %@ AND indentLevel == %@", entry.heading, NSNumber(value: entry.level)))
        XCTAssertEqual(nodes.count, 1, "\(name): expected one node for \(entry)")
        guard let node = nodes.first else { continue }
        XCTAssertEqual(node.todoState ?? "", entry.todo ?? "", "\(name): todo state for \(entry.heading)")
        XCTAssertEqual(node.priority ?? "", entry.priority ?? "", "\(name): priority for \(entry.heading)")
        XCTAssertEqual(node.tags ?? "", entry.tags ?? "", "\(name): tags for \(entry.heading)")
        if let id = entry.id {
          XCTAssertEqual(node.nodeId, id, "\(name): :ID: binding for \(entry.heading)")
        }
      }
    }

    // And the parent wiring: task under epic under category under file node.
    let task = try fetchSingleNode(heading: "Call three contractors for quotes")
    XCTAssertEqual(task.parent?.heading, "Renovate the kitchen")
    XCTAssertEqual(task.parent?.parent?.heading, "Home & Household")
    XCTAssertEqual(task.parent?.parent?.parent?.heading, "home.org.txt")
  }
}
